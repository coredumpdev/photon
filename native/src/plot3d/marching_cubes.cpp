Mesh marching_cubes(const double* values, size_t nx, size_t ny, size_t nz, double level,
                    double x0, double x1, double y0, double y1, double z0, double z1) {
  Mesh mesh;
  if (!values || nx < 2 || ny < 2 || nz < 2) return mesh;
  if (x0 == x1) {
    x0 = 0.0;
    x1 = static_cast<double>(nx - 1);
  }
  if (y0 == y1) {
    y0 = 0.0;
    y1 = static_cast<double>(ny - 1);
  }
  if (z0 == z1) {
    z0 = 0.0;
    z1 = static_cast<double>(nz - 1);
  }

  const auto wx = [&](double x) { return x0 + x / static_cast<double>(nx - 1) * (x1 - x0); };
  const auto wy = [&](double y) { return y0 + y / static_cast<double>(ny - 1) * (y1 - y0); };
  const auto wz = [&](double z) { return z0 + z / static_cast<double>(nz - 1) * (z1 - z0); };
  const auto at = [&](size_t x, size_t y, size_t z) { return values[x + y * nx + z * nx * ny]; };
  // Central difference, pointing toward increasing value; negated below for an
  // outward normal.
  const auto grad = [&](size_t x, size_t y, size_t z) {
    return std::array<double, 3>{
        at(std::min(nx - 1, x + 1), y, z) - at(x == 0 ? 0 : x - 1, y, z),
        at(x, std::min(ny - 1, y + 1), z) - at(x, y == 0 ? 0 : y - 1, z),
        at(x, y, std::min(nz - 1, z + 1)) - at(x, y, z == 0 ? 0 : z - 1),
    };
  };

  std::array<double, 8> corner_value{};
  std::array<std::array<double, 3>, 12> edge_point{};
  std::array<std::array<double, 3>, 12> edge_normal{};

  for (size_t z = 0; z + 1 < nz; ++z) {
    for (size_t y = 0; y + 1 < ny; ++y) {
      for (size_t x = 0; x + 1 < nx; ++x) {
        int cube_index = 0;
        for (int i = 0; i < 8; ++i) {
          corner_value[static_cast<size_t>(i)] =
              at(x + static_cast<size_t>(kCorner[i][0]), y + static_cast<size_t>(kCorner[i][1]),
                 z + static_cast<size_t>(kCorner[i][2]));
          if (corner_value[static_cast<size_t>(i)] < level) cube_index |= 1 << i;
        }
        const int edges = kEdgeTable[cube_index];
        if (edges == 0) continue;

        for (int e = 0; e < 12; ++e) {
          if ((edges & (1 << e)) == 0) continue;
          const int a = kEdgeCorners[e][0];
          const int b = kEdgeCorners[e][1];
          const double va = corner_value[static_cast<size_t>(a)];
          const double vb = corner_value[static_cast<size_t>(b)];
          // Two corners of the same value give no crossing to interpolate, so
          // the midpoint is the only answer that is not a division by zero.
          const double t = std::abs(vb - va) < 1e-9 ? 0.5 : (level - va) / (vb - va);
          const double px = static_cast<double>(x) + kCorner[a][0] +
                            (kCorner[b][0] - kCorner[a][0]) * t;
          const double py = static_cast<double>(y) + kCorner[a][1] +
                            (kCorner[b][1] - kCorner[a][1]) * t;
          const double pz = static_cast<double>(z) + kCorner[a][2] +
                            (kCorner[b][2] - kCorner[a][2]) * t;
          edge_point[static_cast<size_t>(e)] = {wx(px), wy(py), wz(pz)};

          const std::array<double, 3> ga =
              grad(x + static_cast<size_t>(kCorner[a][0]), y + static_cast<size_t>(kCorner[a][1]),
                   z + static_cast<size_t>(kCorner[a][2]));
          const std::array<double, 3> gb =
              grad(x + static_cast<size_t>(kCorner[b][0]), y + static_cast<size_t>(kCorner[b][1]),
                   z + static_cast<size_t>(kCorner[b][2]));
          double nx_n = -(ga[0] + (gb[0] - ga[0]) * t);
          double ny_n = -(ga[1] + (gb[1] - ga[1]) * t);
          double nz_n = -(ga[2] + (gb[2] - ga[2]) * t);
          const double len = std::sqrt(nx_n * nx_n + ny_n * ny_n + nz_n * nz_n);
          const double d = len == 0.0 ? 1.0 : len;
          edge_normal[static_cast<size_t>(e)] = {nx_n / d, ny_n / d, nz_n / d};
        }

        for (int i = 0; i < 16 && kTriTable[cube_index][i] >= 0; i += 3) {
          for (int k = 0; k < 3; ++k) {
            const size_t e = static_cast<size_t>(kTriTable[cube_index][i + k]);
            mesh.positions.insert(mesh.positions.end(),
                                  {static_cast<float>(edge_point[e][0]),
                                   static_cast<float>(edge_point[e][1]),
                                   static_cast<float>(edge_point[e][2])});
            mesh.normals.insert(mesh.normals.end(),
                                {static_cast<float>(edge_normal[e][0]),
                                 static_cast<float>(edge_normal[e][1]),
                                 static_cast<float>(edge_normal[e][2])});
          }
        }
      }
    }
  }
  return mesh;
}

